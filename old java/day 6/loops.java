class loops{
    public static void main(String[] args) {
        // for loop
         int i = 0;
        for (i=0; i < 11; i=i+1){
            System.out.println(i);
    }

        
    
    
    // while loop
        int j=0;
        while (j<11){
            System.out.println(j);
            j++;
        }
    
    
    
        // do while  loop 
        int k=0;
        do{
            System.out.println(k);
            k++;
        }while(k<11);


        
    }
}